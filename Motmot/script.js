function showMusicError(message) {
  musicStatus.textContent = message;
  musicStatus.className = 'music-feedback';
}

function fadeAudioTo(targetVolume, duration, onComplete) {
  window.cancelAnimationFrame(volumeFadeId);
  const generation = ++volumeFadeGeneration;
  if (reducedMotion || document.hidden || duration === 0) {
    audio.volume = targetVolume;
    if (onComplete) onComplete();
    return;
  }
  const startVolume = audio.volume;
  const startedAt = performance.now();

  const step = (now) => {
    if (generation !== volumeFadeGeneration) return;
    const progress = duration === 0 ? 1 : Math.min((now - startedAt) / duration, 1);
    audio.volume = startVolume + (targetVolume - startVolume) * progress;
    if (progress < 1) {
      volumeFadeId = window.requestAnimationFrame(step);
    } else if (onComplete) {
      onComplete();
    }
  };

  volumeFadeId = window.requestAnimationFrame(step);
}

function pauseBackgroundMusic(duration = 450) {
  playbackGeneration += 1;
  if (backgroundPausePromise) return backgroundPausePromise;
  if (audio.paused) {
    window.cancelAnimationFrame(volumeFadeId);
    volumeFadeGeneration += 1;
    audio.volume = backgroundVolume;
    if (pendingBackgroundPlay) {
      return pendingBackgroundPlay.then(() => {
        audio.pause();
      });
    }
    return Promise.resolve();
  }

  const pauseAttempt = new Promise((resolve) => {
    fadeAudioTo(0, reducedMotion ? 0 : duration, () => {
      audio.pause();
      audio.volume = backgroundVolume;
      resolve();
    });
  });
  const trackedPause = pauseAttempt.finally(() => {
    if (backgroundPausePromise === trackedPause) backgroundPausePromise = null;
  });
  backgroundPausePromise = trackedPause;
  return trackedPause;
}

function canPlayBackgroundMusic() {
  const openCard = $('.song-card.player-open');
  if (!openCard) return true;
  const songAudio = openCard.querySelector('audio');
  return Boolean(songAudio && songAudio.paused);
}

function startBackgroundMusic() {
  if (!musicEnabled || !canPlayBackgroundMusic()) return Promise.resolve(false);
  if (backgroundPausePromise) {
    return backgroundPausePromise.then(() => startBackgroundMusic());
  }
  if (!audio.paused) return Promise.resolve(true);
  if (pendingBackgroundPlay) return pendingBackgroundPlay;

  audio.volume = Math.min(audio.volume || backgroundVolume, 0.03);
  const generation = ++playbackGeneration;
  let playRequest;
  try {
    playRequest = audio.play();
  } catch (error) {
    playRequest = Promise.reject(error);
  }

  const attempt = Promise.resolve(playRequest).then(() => {
    if (generation !== playbackGeneration || !musicEnabled || !canPlayBackgroundMusic()) {
      audio.pause();
      return false;
    }
    fadeAudioTo(backgroundVolume, reducedMotion ? 0 : 1000);
    musicStatus.textContent = 'Background music is playing.';
    musicStatus.className = 'sr-only';
    welcomeStatus.textContent = '';
    updateMusicButton();
    return true;
  }).catch((error) => {
    audio.volume = backgroundVolume;
    const errorName = error && typeof error === 'object' && 'name' in error ? error.name : '';
    const errorMessage = error instanceof Error ? error.message : String(error);
    if (errorName === 'NotAllowedError') {
      welcomeStatus.textContent = 'Tap to begin the music and open my surprise to you.';
      if (!welcomeOverlay.open || welcomeOverlay.classList.contains('is-closing')) {
        showMusicError('Your browser blocked background playback. Tap Music on to try again.');
      } else {
        musicStatus.textContent = 'Tap the welcome button to start background music.';
      }
    } else {
      welcomeStatus.textContent = 'The background music could not be loaded. You can still open your surprise.';
      showMusicError(`Background music could not start: ${errorMessage}`);
    }
    updateMusicButton();
    return false;
  }).finally(() => {
    if (pendingBackgroundPlay === attempt) pendingBackgroundPlay = null;
  });
  pendingBackgroundPlay = attempt;
  return attempt;
}

function pauseBackgroundForSong() {
  return pauseBackgroundMusic(350);
}

function resumeBackgroundAfterSong(nativeSongPaused = false) {
  if (!musicEnabled || (!nativeSongPaused && !canPlayBackgroundMusic())) return;
  if (backgroundPausePromise) {
    void backgroundPausePromise.then(() => {
      if (musicEnabled && (nativeSongPaused ? canPlayBackgroundMusic() : !$('.song-card.player-open'))) {
        void startBackgroundMusic();
      }
    });
  } else {
    void startBackgroundMusic();
  }
}

