const musicStatus = $('#music-status');
const backgroundVolume = CONFIG.backgroundMusic.volume;
let musicEnabled = true;
let volumeFadeId = 0;
let volumeFadeGeneration = 0;
let playbackGeneration = 0;
let pendingBackgroundPlay = null;
let backgroundPausePromise = null;
